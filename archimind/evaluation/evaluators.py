import re
from typing import Dict, List, Tuple

from archimind.api.schemas import DocumentChunkModel
from archimind.rag.prompt import INSUFFICIENT_EVIDENCE_FALLBACK


class FaithfulnessEvaluator:
    """Measures whether the claims in the generated answer are strictly grounded in retrieved chunks."""

    def evaluate(
        self,
        answer: str,
        retrieved_chunks: List[DocumentChunkModel],
        is_sufficient_evidence: bool,
    ) -> Tuple[float, str]:
        """Evaluates faithfulness score [0.0 - 1.0]."""
        if not is_sufficient_evidence or answer == INSUFFICIENT_EVIDENCE_FALLBACK:
            # If the engine correctly abstained due to lack of evidence, it is 100% faithful
            return 1.0, "Engine correctly identified insufficient evidence without hallucinating."

        if not retrieved_chunks:
            # Claims made with zero context is complete hallucination
            return 0.0, "Answer generated claims despite having zero retrieved context chunks."

        # Concatenate context
        context_corpus = " ".join([c.content.lower() for c in retrieved_chunks])

        # Extract technical claims / sentences from answer
        # Strip introductory boilerplate and citation brackets
        clean_ans = re.sub(r"\[(?:Doc\s*)?\d+\]", "", answer)
        sentences = [
            s.strip()
            for s in re.split(r"(?<=[.!?]) +", clean_ans)
            if len(s.strip()) > 15 and "based on the technical" not in s.lower()
        ]

        if not sentences:
            return 1.0, "Answer contained no distinct claims to refute."

        grounded_count = 0
        reasons = []

        for sent in sentences:
            # Extract content words (length >= 4)
            words = [
                w.lower().strip(".,;:()\"'")
                for w in sent.split()
                if len(w) >= 4
                and w.lower()
                not in {"this", "that", "with", "from", "here", "operates", "using", "into"}
            ]
            if not words:
                continue

            matches = sum(1 for w in words if w in context_corpus)
            overlap_ratio = matches / len(words)

            # A sentence is considered grounded if >= 65% of its technical keywords appear in context
            if overlap_ratio >= 0.65:
                grounded_count += 1
            else:
                reasons.append(f"Claim not fully supported by context: '{sent[:60]}...'")

        score = grounded_count / len(sentences) if sentences else 1.0
        reason = (
            f"{grounded_count}/{len(sentences)} sentences grounded in retrieved evidence."
            if not reasons
            else "; ".join(reasons)
        )
        return round(score, 4), reason


class AnswerCorrectnessEvaluator:
    """Measures whether the generated answer captures reference facts and expected technical concepts."""

    def evaluate(
        self,
        generated_answer: str,
        ground_truth_answer: str,
        expected_keywords: List[str],
        is_answerable: bool,
    ) -> Tuple[float, str]:
        """Evaluates answer correctness score [0.0 - 1.0]."""
        gen_lower = generated_answer.lower()

        # Case 1: Unanswerable / out-of-scope question
        if not is_answerable:
            if (
                "not have enough evidence" in gen_lower
                or "insufficient evidence" in gen_lower
                or generated_answer == INSUFFICIENT_EVIDENCE_FALLBACK
            ):
                return 1.0, "Correctly identified unanswerable question and returned insufficient evidence fallback."
            else:
                return 0.0, "Failed to identify out-of-scope question and hallucinated an answer."

        # Case 2: Answerable question
        if (
            "not have enough evidence" in gen_lower
            or "insufficient evidence" in gen_lower
            or generated_answer == INSUFFICIENT_EVIDENCE_FALLBACK
        ):
            # False negative: gave fallback when reference answer existed
            return 0.0, "Engine falsely abstained on an answerable question."

        # Keyword recall
        matched_keywords = [kw for kw in expected_keywords if kw.lower() in gen_lower]
        keyword_recall = (
            len(matched_keywords) / len(expected_keywords) if expected_keywords else 1.0
        )

        # Token set overlap with ground truth
        gt_words = set(
            w.lower().strip(".,;:()\"'")
            for w in ground_truth_answer.split()
            if len(w) >= 4
        )
        gen_words = set(
            w.lower().strip(".,;:()\"'")
            for w in generated_answer.split()
            if len(w) >= 4
        )

        overlap = len(gt_words.intersection(gen_words)) / len(gt_words) if gt_words else 1.0

        # Weighted combination: 60% expected technical keyword recall + 40% lexical semantic overlap
        score = (0.6 * keyword_recall) + (0.4 * overlap)
        reason = (
            f"Matched {len(matched_keywords)}/{len(expected_keywords)} expected keywords; "
            f"Ground truth overlap {overlap:.2f}."
        )
        return round(min(score, 1.0), 4), reason
